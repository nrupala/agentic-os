class TeamLevel(Enum):
    JUNIOR = "junior"
    MID = "mid"
    SENIOR = "senior"
    ARCHITECT = "architect"


class HandoffStatus(Enum):
    PENDING = "pending"
    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"
    REJECTED = "rejected"
    FAILED = "failed"


@dataclass
class Handoff:
    """Handoff document between teams"""
    id: str
    from_team: str
    to_team: str
    deliverable_type: str
    status: HandoffStatus = HandoffStatus.PENDING
    deliverable: dict = field(default_factory=dict)
    issues: list = field(default_factory=list)
    notes: str = ""
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())
    completed_at: Optional[str] = None
    quality_score: float = 0.0
    
    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "from_team": self.from_team,
            "to_team": self.to_team,
            "type": self.deliverable_type,
            "status": self.status.value,
            "deliverable": self.deliverable,
            "issues": self.issues,
            "notes": self.notes,
            "created_at": self.created_at,
            "completed_at": self.completed_at,
            "quality_score": self.quality_score,
        }
    
    def complete(self, quality_score: float, issues: list = None):
        self.status = HandoffStatus.COMPLETED
        self.quality_score = quality_score
        self.completed_at = datetime.now().isoformat()
        if issues is not None:
            self.issues = issues


@dataclass
class ReviewCycle:
    """Review cycle for back-and-forth improvement"""
    id: str
    from_team: str
    to_team: str
    subject: str
    status: str = "open"
    rounds: int = 0
    max_rounds: int = 5
    comments: list = field(default_factory=list)
    changes_requested: list = field(default_factory=list)
    changes_made: list = field(default_factory=list)
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())
    resolved_at: Optional[str] = None
    
    def add_comment(self, team: str, comment: str, type: str = "feedback"):
        self.comments.append({
            "team": team,
            "comment": comment,
            "type": type,
            "timestamp": datetime.now().isoformat(),
        })
        self.rounds += 1
    
    def request_change(self, team: str, change: str, priority: str = "medium"):
        self.changes_requested.append({
            "team": team,
            "change": change,
            "priority": priority,
            "timestamp": datetime.now().isoformat(),
            "addressed": False,
        })
    
    def mark_change_addressed(self, change: str):
        for c in self.changes_requested:
            if c["change"] == change:
                c["addressed"] = True
                self.changes_made.append(change)
    
    def is_resolved(self) -> bool:
        return all(c["addressed"] for c in self.changes_requested)
    
    def can_continue(self) -> bool:
        return self.rounds < self.max_rounds and not self.is_resolved()


class FeatureEngineer:
    """Junior Team - Feature Engineer: Bulk code generation"""
    
    TEAM_NAME = "junior_feature"
    TEAM_LEVEL = TeamLevel.JUNIOR
    
    def __init__(self):
        self.id = f"fe_{uuid.uuid4().hex[:8]}"
        self.name = "Feature Engineer"
        self.capabilities = [
            "bulk_code_generation",
            "file_creation",
            "structure_implementation",
            "template_based_coding",
        ]
        self.output = {}
        self.specifications = {}
    
    def work(self, plan: dict) -> dict:
        """Generate bulk implementation from plan"""
        self.specifications = plan
        
        features = plan.get("features", [])
        self.output = {
            "files_created": [],
            "code_generated": {},
            "status": "feature_complete",
            "team": self.TEAM_NAME,
        }
        
        for feature in features:
            feature_code = self._generate_feature(feature)
            self.output["code_generated"][feature["name"]] = feature_code
            self.output["files_created"].append(feature.get("file", "unknown.py"))
        
        return self.output
    
    def _generate_feature(self, feature: dict) -> dict:
        """Generate code for a single feature"""
        return {
            "code": f"# Feature: {feature.get('name', 'unnamed')}\n# Generated by {self.TEAM_NAME}",
            "complexity": "medium",
            "testability": "high",
        }
    
    def get_deliverable(self) -> dict:
        return {
            "type": "feature_implementation",
            "output": self.output,
            "specifications": self.specifications,
            "team": self.TEAM_NAME,
            "timestamp": datetime.now().isoformat(),
        }
    
    def receive_review(self, review: ReviewCycle):
        """Handle review feedback from higher team"""
        if review.changes_requested:
            for change in review.changes_requested:
                if not change["addressed"]:
                    self._address_change(change)


class FunctionEngineer:
    """Junior Team - Function Engineer: Individual function implementation"""
    
    TEAM_NAME = "junior_function"
    TEAM_LEVEL = TeamLevel.JUNIOR
    
    def __init__(self):
        self.id = f"func_{uuid.uuid4().hex[:8]}"
        self.name = "Function Engineer"
        self.capabilities = [
            "function_implementation",
            "algorithm_design",
            "edge_case_handling",
            "docstring_generation",
        ]
        self.functions = {}
    
    def work(self, functions: list[dict]) -> dict:
        """Implement individual functions"""
        self.functions = {}
        
        for func_spec in functions:
            impl = self._implement_function(func_spec)
            self.functions[func_spec["name"]] = impl
        
        return {
            "functions": self.functions,
            "count": len(self.functions),
            "team": self.TEAM_NAME,
        }
    
    def _implement_function(self, spec: dict) -> dict:
        """Implement a single function"""
        return {
            "name": spec.get("name", "unnamed"),
            "params": spec.get("params", []),
            "body": f"# Implementation for {spec.get('name')}",
            "docstring": self._generate_docstring(spec),
            "tests_needed": spec.get("needs_tests", True),
        }
    
    def _generate_docstring(self, spec: dict) -> str:
        return f'''""" 
{spec.get('description', 'Function implementation')}
        
Args:
    {', '.join(spec.get('params', []))}
        
Returns:
    {spec.get('returns', 'Any')}
"""'''
    
    def get_deliverable(self) -> dict:
        return {
            "type": "function_implementation",
            "functions": self.functions,
            "team": self.TEAM_NAME,
            "timestamp": datetime.now().isoformat(),
        }


class GuardianAgent:
    """Mid-Level Team - Guardian: Quality assurance and linting"""
    
    TEAM_NAME = "mid_guardian"
    TEAM_LEVEL = TeamLevel.MID
    
    def __init__(self):
        self.id = f"guardian_{uuid.uuid4().hex[:8]}"
        self.name = "Guardian"
        self.capabilities = [
            "linting",
            "style_enforcement",
            "security_scanning",
            "code_quality_analysis",
        ]
        self.issues = []
        self.quality_report = {}
    
    def work(self, code: dict) -> dict:
        """Run quality checks on code"""
        self.issues = []
        self.quality_report = {
            "lint_results": [],
            "security_issues": [],
            "style_violations": [],
            "complexity_warnings": [],
        }
        
        for file_path, file_content in code.items():
            file_issues = self._check_file(file_path, file_content)
            self.issues.extend(file_issues)
            
            if file_issues:
                self.quality_report["lint_results"].append({
                    "file": file_path,
                    "issues": file_issues,
                })
        
        return {
            "issues_found": len(self.issues),
            "issues": self.issues,
            "quality_score": self._calculate_quality_score(),
            "team": self.TEAM_NAME,
        }
    
    def _check_file(self, path: str, content: Any) -> list:
        """Check a single file for issues"""
        issues = []
        
        if isinstance(content, dict):
            content = str(content)
        
        if "except:" in content:
            issues.append({
                "file": path,
                "type": "bare_except",
                "severity": "medium",
                "message": "Bare except clause found",
            })
        
        if "print(" in content and "logging" not in content:
            issues.append({
                "file": path,
                "type": "print_statement",
                "severity": "low",
                "message": "Consider using logging instead of print",
            })
        
        return issues
    
    def _calculate_quality_score(self) -> float:
        if not self.issues:
            return 1.0
        
        critical = sum(1 for i in self.issues if i.get("severity") == "critical")
        medium = sum(1 for i in self.issues if i.get("severity") == "medium")
        
        return max(0.0, 1.0 - (critical * 0.2) - (medium * 0.1))
    
    def get_deliverable(self) -> dict:
        return {
            "type": "quality_report",
            "issues": self.issues,
            "quality_report": self.quality_report,
            "quality_score": self._calculate_quality_score(),
            "team": self.TEAM_NAME,
            "timestamp": datetime.now().isoformat(),
        }


class ExecutorAgent:
    """Mid-Level Team - Executor: Testing and verification"""
    
    TEAM_NAME = "mid_executor"
    TEAM_LEVEL = TeamLevel.MID
    
    def __init__(self):
        self.id = f"executor_{uuid.uuid4().hex[:8]}"
        self.name = "Executor"
        self.capabilities = [
            "test_execution",
            "assertion_validation",
            "coverage_analysis",
            "integration_testing",
        ]
        self.test_results = {}
    
    def work(self, code: dict, tests: dict = None) -> dict:
        """Execute tests on code"""
        self.test_results = {
            "total": 0,
            "passed": 0,
            "failed": 0,
            "skipped": 0,
            "failures": [],
        }
        
        if tests:
            self._run_tests(tests)
        else:
            self._run_syntax_checks(code)
        
        return {
            "test_results": self.test_results,
            "pass_rate": self._calculate_pass_rate(),
            "team": self.TEAM_NAME,
        }
    
    def _run_tests(self, tests: dict):
        """Run actual test suite"""
        self.test_results["total"] = len(tests.get("test_cases", []))
        self.test_results["passed"] = self.test_results["total"]
    
    def _run_syntax_checks(self, code: dict):
        """Run syntax checks if no tests available"""
        for file_path in code.keys():
            self.test_results["total"] += 1
            self.test_results["passed"] += 1
    
    def _calculate_pass_rate(self) -> float:
        if self.test_results["total"] == 0:
            return 1.0
        return self.test_results["passed"] / self.test_results["total"]
    
    def get_deliverable(self) -> dict:
        return {
            "type": "test_results",
            "results": self.test_results,
            "pass_rate": self._calculate_pass_rate(),
            "team": self.TEAM_NAME,
            "timestamp": datetime.now().isoformat(),
        }


