class SecurityEngineer:
    """Senior Team - Security review and hardening"""
    
    TEAM_NAME = "senior_security"
    TEAM_LEVEL = TeamLevel.SENIOR
    
    def __init__(self):
        self.id = f"sec_{uuid.uuid4().hex[:8]}"
        self.name = "Security Engineer"
        self.capabilities = [
            "vulnerability_scanning",
            "security_audit",
            "hardening",
            "compliance_check",
        ]
    
    def work(self, code: dict) -> dict:
        """Security audit on code"""
        vulnerabilities = []
        
        for file_path, content in code.items():
            vuln = self._scan_vulnerabilities(file_path, content)
            vulnerabilities.extend(vuln)
        
        return {
            "vulnerabilities": vulnerabilities,
            "risk_level": self._calculate_risk_level(vulnerabilities),
            "team": self.TEAM_NAME,
        }
    
    def _scan_vulnerabilities(self, path: str, content: Any) -> list:
        """Scan for security vulnerabilities"""
        vuln = []
        
        if isinstance(content, dict):
            return vuln
        
        if "eval(" in content:
            vuln.append({
                "file": path,
                "type": "code_injection",
                "severity": "critical",
                "message": "eval() usage detected - potential code injection",
            })
        
        if "password" in content.lower() or "api_key" in content.lower():
            vuln.append({
                "file": path,
                "type": "secret_exposure",
                "severity": "high",
                "message": "Potential hardcoded secret detected",
            })
        
        return vuln
    
    def _calculate_risk_level(self, vulnerabilities: list) -> str:
        if any(v.get("severity") == "critical" for v in vulnerabilities):
            return "CRITICAL"
        if any(v.get("severity") == "high" for v in vulnerabilities):
            return "HIGH"
        if vulnerabilities:
            return "MEDIUM"
        return "LOW"
    
    def get_deliverable(self) -> dict:
        return {
            "type": "security_audit",
            "team": self.TEAM_NAME,
            "timestamp": datetime.now().isoformat(),
        }


