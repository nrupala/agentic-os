@app.post("/register")
def register(user: UserCreate):
    conn = get_db()
    password_hash = auth.hash_password(user.password)
    try:
        conn.execute("INSERT INTO users (username, password_hash) VALUES (?, ?)",
                    (user.username, password_hash))
        conn.commit()
        return {"message": "Registered"}
    except sqlite3.IntegrityError:
        raise HTTPException(400, "Username exists")
    finally:
        conn.close()

@app.post("/token")
def get_token(req: TokenRequest):
    conn = get_db()
    user = conn.execute("SELECT * FROM users WHERE username = ?", (req.username,)).fetchone()
    conn.close()
    if not user:
        raise HTTPException(401, "Invalid credentials")
    if auth.hash_password(req.password) != user['password_hash']:
        raise HTTPException(401, "Invalid credentials")
    return {"user_id": user['id']}

@app.post("/upload")
async def upload(file: UploadFile = File(...), token: str = ""):
    tok = auth.verify_token(token, "upload")
    if not tok:
        raise HTTPException(401, "Invalid token")
    
    file_id = secrets.token_urlsafe(16)
    contents = await file.read()
    
    if encryptor:
        nonce, ciphertext = encryptor.encrypt(contents)
        enc_path = STORAGE_DIR / f"{file_id}.enc"
        enc_path.write_bytes(nonce + ciphertext)
    else:
        enc_path = STORAGE_DIR / file_id
        enc_path.write_bytes(contents)
    
    conn = get_db()
    conn.execute("INSERT INTO files VALUES (?, ?, ?, ?, ?, NULL, ?)",
                (file_id, tok['user_id'], file.filename, len(contents), str(enc_path), datetime.now().isoformat()))
    conn.commit()
    conn.close()
    
    download_token = auth.create_token(tok['user_id'], file_id, "download")
    return {"file_id": file_id, "token": download_token, "expires_at": (datetime.now() + timedelta(hours=24)).isoformat()}

@app.get("/download/{file_id}")
def download(file_id: str, token: str = ""):
    tok = auth.verify_token(token, "download")
    if not tok:
        raise HTTPException(401, "Invalid token")
    
    conn = get_db()
