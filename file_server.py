class AuthManager:
    def __init__(self):
        self.rate_limit = defaultdict(list)
    
    def hash_password(self, password: str) -> str:
        return hashlib.sha256(password.encode()).hexdigest()
    
    def create_token(self, user_id: int, file_id: str, operation: str) -> str:
        token = secrets.token_urlsafe(32)
        expires = datetime.now() + timedelta(hours=24)
        conn = get_db()
        conn.execute("INSERT INTO tokens VALUES (?, ?, ?, ?, ?)",
                    (token, user_id, file_id, operation, expires.isoformat()))
        conn.commit()
        conn.close()
        return token
    
    def verify_token(self, token: str, operation: str = None) -> Optional[dict]:
        conn = get_db()
        tok = conn.execute("SELECT * FROM tokens WHERE token = ?", (token,)).fetchone()
        conn.close()
        if not tok:
            return None
        if datetime.fromisoformat(tok['expires_at']) < datetime.now():
            return None
        if operation and tok['operation'] != operation:
            return None
        return dict(tok)
    
    def check_rate_limit(self, ip: str) -> bool:
        now = time.time()
        self.rate_limit[ip] = [t for t in self.rate_limit[ip] if now - t < 60]
        if len(self.rate_limit[ip]) >= 100:
            return False
        self.rate_limit[ip].append(now)
        return True

auth = AuthManager()

